# A merge that drops and makes a table again as the same relation (a
# definition ALTER can't change in place: an identity or a generation
# added or changed, a column added before a kept one, columns in another
# order) writes every row of it: the table made again keeps its own OID,
# but its indexes, TOAST table and change log are new relations, so the
# rows step reads it as the empty table it is, not as the one the working
# set's baseline knew.  (Only a table the branch had none of as the move
# began, brought back, is made again as every relation it was.)  Each
# case merges a side that changed the table's definition and its rows into
# main, which changed another table, and then one where main changed a
# row of the table too.

use strict;
use warnings FATAL => 'all';
use PostgreSQL::Test::Cluster;
use PostgreSQL::Test::Utils;
use Test::More;

my $node = PostgreSQL::Test::Cluster->new('merge_remade_rows');
$node->init;
$node->append_conf('postgresql.conf', q{
wal_level = replica
autovacuum = off
prolly_fold_worker = off
fsync = off
});
$node->start;

sub sql { return $node->safe_psql('postgres', $_[0]); }

# (the last line: a checkout's own output comes first)
sub on
{
	my ($branch, $q) = @_;
	my @out = split /\n/, sql(qq{SELECT dolt_checkout('$branch') IS NOT NULL; $q});
	return $out[-1];
}

my $n = 0;
# a table d$n.t, the side's definition change $change of it with a new row,
# merged into main; $main_row: main changes row 7 of it too
sub case
{
	my ($what, $create, $change, $main_row) = @_;
	$n++;
	my $s = "d$n";
	my $digest = qq{SELECT count(*) || ':' || md5(string_agg(id || ':' || v, ',' ORDER BY id)) FROM $s.t};

	my $made = $create =~ s/\@T\@/$s.t/gr;
	sql(qq{SELECT dolt_checkout('main') IS NOT NULL;
		CREATE SCHEMA $s VERSIONED;
		$made;
		CREATE TABLE $s.u (id int PRIMARY KEY);
		INSERT INTO $s.t (id, x, v) SELECT g, g, md5(g::text) FROM generate_series(1, 1000) g;
		SELECT dolt_commit('-Am', 'c0 $n') IS NOT NULL;
		SELECT dolt_branch('side$n') IS NOT NULL});
	my $c = $change =~ s/\@T\@/$s.t/gr;
	on("side$n", qq{$c;
		INSERT INTO $s.t (id, x, v) VALUES (5000, 5000, 'side new');
		UPDATE $s.t SET v = 'side5' WHERE id = 5;
		SELECT dolt_commit('-am', 'side $n') IS NOT NULL});
	my $want = on("side$n", $main_row
		? qq{SELECT count(*) || ':' || md5(string_agg(id || ':' ||
			CASE WHEN id = 7 THEN 'main7' ELSE v END, ',' ORDER BY id)) FROM $s.t}
		: $digest);
	on('main', qq{INSERT INTO $s.u VALUES (1);}
		  . ($main_row ? qq{UPDATE $s.t SET v = 'main7' WHERE id = 7;} : '')
		  . qq{SELECT dolt_commit('-am', 'main $n') IS NOT NULL});
	my ($ret, $out, $err) = $node->psql('postgres',
		qq{SELECT dolt_checkout('main') IS NOT NULL;
		SELECT 'merged ' || ((dolt_merge('side$n'))[1] IS NOT NULL)});
	like($out, qr/merged t/, "$what: the merge finished");
	unlike($err, qr/ERROR/, "$what: with no error");
	is(on('main', $digest), $want, "$what: every row is there, as merged");
	is(on('main', q{SELECT count(*) FROM dolt_status}), '0',
		"$what: the merge's commit holds them");
}

my $plain = q{CREATE TABLE @T@ (id int PRIMARY KEY, x int NOT NULL, v text)};
for my $main_row (0, 1)
{
	my $both = $main_row ? ', both sides changing rows' : '';
	case("identity added$both", $plain,
		q{ALTER TABLE @T@ ALTER COLUMN x ADD GENERATED BY DEFAULT AS IDENTITY},
		$main_row);
	case("generation changed$both",
		q{CREATE TABLE @T@ (id int PRIMARY KEY, x int NOT NULL, v text,
			g int GENERATED ALWAYS AS (x * 2) STORED)},
		q{ALTER TABLE @T@ ALTER COLUMN g SET EXPRESSION AS (x * 3)}, $main_row);
	case("a column added before a kept one$both", $plain,
		q{ALTER TABLE @T@ ADD COLUMN w int; ALTER TABLE @T@ RENAME COLUMN v TO v_was;
		  ALTER TABLE @T@ ADD COLUMN v text; UPDATE @T@ SET v = v_was;
		  ALTER TABLE @T@ DROP COLUMN v_was}, $main_row);
	case("columns in another order$both", $plain,
		q{ALTER TABLE @T@ RENAME COLUMN x TO x_was; ALTER TABLE @T@ ADD COLUMN x int;
		  UPDATE @T@ SET x = x_was; ALTER TABLE @T@ DROP COLUMN x_was;
		  ALTER TABLE @T@ ALTER COLUMN x SET NOT NULL}, $main_row);
}

$node->stop;
done_testing();
