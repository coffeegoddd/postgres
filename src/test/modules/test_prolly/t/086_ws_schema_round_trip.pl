my $tag_on = sub {
	my ($on, $table, $column) = @_;
	return $node->safe_psql('postgres', qq{
		SET catalog_branch = $on;
		SELECT attcoltag FROM pg_attribute WHERE attrelid = '$table'::regclass AND attname = '$column'});
