-- Identity and generated columns: identity columns ALWAYS and BY DEFAULT
-- with their own sequence settings, stored generated columns that call a
-- user function (which counts its calls), one in an index, one under a
-- CHECK, one NULL, a virtual one, and a keyless table with one.
CREATE SCHEMA rt;
SET search_path = rt, public;

CREATE FUNCTION scale(int) RETURNS int IMMUTABLE LANGUAGE plpgsql AS $$
BEGIN
	PERFORM nextval('public.vc_gen_calls');
	RETURN $1 * 10;
END $$;

CREATE TABLE item (
	id int GENERATED ALWAYS AS IDENTITY (START WITH 100 INCREMENT BY 5) PRIMARY KEY,
	a int,
	b text,
	g int GENERATED ALWAYS AS (rt.scale(a)) STORED CHECK (g >= 0),
	k text GENERATED ALWAYS AS (upper(b) || ':' || a) STORED,
	v int GENERATED ALWAYS AS (a + 1) VIRTUAL
);
CREATE INDEX item_g ON item (g);
CREATE UNIQUE INDEX item_k ON item (k);

CREATE TABLE byd (
	id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	a int NOT NULL,
	sq int GENERATED ALWAYS AS (a * a) STORED
);

CREATE TABLE bag (x int, gx int GENERATED ALWAYS AS (rt.scale(x)) STORED);

